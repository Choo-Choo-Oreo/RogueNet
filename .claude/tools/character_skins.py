def parse(text):
    rows = text.strip('\n').split('\n')
    assert len(rows) == 16, len(rows)
    for r in rows:
        assert len(r) == 16, r
    return [list(r) for r in rows]

def blank():
    return [['.'] * 16 for _ in range(16)]

def put(g, x, y, c):
    if 0 <= x < 16 and 0 <= y < 16 and c != '.':
        g[y][x] = c

def outline(g):
    """Close the outline around anything the leg moves opened (4-neighbours)."""
    add = []
    for y in range(16):
        for x in range(16):
            if g[y][x] == '.' and any(0 <= x + dx < 16 and 0 <= y + dy < 16 and g[y + dy][x + dx] not in '.0'
                                      for dx, dy in ((1,0),(-1,0),(0,1),(0,-1))):
                add.append((x, y))
    for x, y in add:
        g[y][x] = '0'
    return g

def in_legs(x, legs):
    return legs is not None and legs[0] <= x <= legs[-1]

def upper(stand, hip, legs, dy):
    """Everything but the legs, moved down dy."""
    g = blank()
    for y in range(16):
        for x in range(16):
            if y > hip and in_legs(x, legs):
                continue
            put(g, x, y + dy, stand[y][x])
    return g

def front_step(stand, hip, legs, lifted):
    """A dip frame: body down 1px, one leg planted (shin 1 shorter), the other lifted."""
    x0, split, x1 = legs
    g = upper(stand, hip, legs, 1)
    n = 15 - hip
    sides = {'left': range(x0, split + 1), 'right': range(split, x1 + 1)}
    planted = 'right' if lifted == 'left' else 'left'
    for x in sides[lifted]:           # its last n-2 rows, one row up
        for i in range(n - 2):
            put(g, x, hip + 2 + i, stand[16 - (n - 2) + i][x])
    for x in sides[planted]:          # its last n-1 rows, in place
        for y in range(hip + 2, 16):
            if stand[y][x] != '.':
                g[y][x] = stand[y][x]
    return g

def dark(c):
    if isinstance(c, tuple):   # a gear colour (character_gear.py)
        return tuple(round(v * FAR) for v in c)
    return c if c in '.0' else c + '~'

def side_leg(g, stand, hip, legs, top, shift_to, far):
    """Draw the side view's leg strip from row `top` down, sheared so its foot moves shift_to px."""
    x0, x1 = legs
    rows = list(range(hip + 1 + (top - hip - 1), 16))
    src = list(range(16 - len(rows), 16))
    for i, (y, sy) in enumerate(zip(rows, src)):
        s = round(shift_to * (i + 1) / len(rows))
        for x in range(x0, x1 + 1):
            c = stand[sy][x]
            if c != '.':
                put(g, x + s, y, dark(c) if far else c)

def frames(skin, view):
    info = D[skin]
    spec = info['views'][view]
    over = parse(spec[2]) if len(spec) > 2 else None
    return walk(parse(spec[1]), info, view, spec[0], over)

def walk(stand, info, view, legs, over=None, gear=False):
    """The 4 walk frames of a standing grid on a body (info = its D entry). gear=True: a gear
    layer on that body: it moves the same way, but gets no outline of its own and is hidden
    where the body's `over` (a tail hanging over the legs) is drawn."""
    hip = info['hip']
    out = []
    for f in range(4):
        dip = f % 2
        if info.get('skirt'):
            g = upper(stand, hip, None, 0) if not dip else skirt_step(stand, hip, 1 if f == 1 else -1)
        elif view == 'Right':
            g = upper(stand, hip, legs, dip)
            if f == 0:
                side_leg(g, stand, hip, legs, hip + 1, 0, False)
            elif f == 2:   # passing: the far foot lifts behind
                far = blank()
                side_leg(far, stand, hip, legs, hip + 1, 0, True)
                for y in range(16):
                    for x in range(16):
                        put(g, x - 1, y - 1, far[y][x]) if y > hip + 1 else None
                side_leg(g, stand, hip, legs, hip + 1, 0, False)
            else:          # stride: near forward on 1, back on 3; far the other way
                s = min(2, 14 - hip) * (1 if f == 1 else -1)   # short legs, short stride
                side_leg(g, stand, hip, legs, hip + 2, -s, True)
                side_leg(g, stand, hip, legs, hip + 2, s, False)
        else:
            g = front_step(stand, hip, legs, 'right' if f == 1 else 'left') if dip else upper(stand, hip, None, 0)
        if over:
            for y in range(16):
                for x in range(16):
                    if gear and over[y][x] != '.' and 0 <= y + dip < 16:
                        g[y + dip][x] = '.'
                    elif not gear:
                        put(g, x, y + dip, over[y][x])
        out.append(g if gear else outline(g))
    return out

